package DataTypes_Variables;

public class DataTypes {

	public static void main(String[] args) {
		
		int i =10; // int stores only numbers
		System.out.println(i);
		
		double d= 2.13; // double stores only floating values
		System.out.println(d);
		
		boolean b = true; // boolean stores only true or false values.
		System.out.println(b);
		
		String name="Vasu"; // String stores alphabets.
		System.out.println(name);
		
		char c='A'; // char stores only one letter.
		System.out.println(c);
		
		float f= 23.113f; // float stores floating values ending 'f' should be there.
		System.out.println(f);
		
		long l = 123456l;  // long stores lengthy numbers ending 'l' should be there.
		System.out.println(l);
	}
}
